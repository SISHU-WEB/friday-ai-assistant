export type TranslationKey = keyof typeof translations.en

interface I18nContextType {
  language: Language
  setLanguage: (lang: Language) => void
  t: (key: TranslationKey, vars?: Record<string, string | number>) => string
}

const I18nContext = createContext<I18nContextType | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  // Synchronous init so the first frame already matches the saved language
  // (no English flash for zh users, U-4).
  const [language, setLanguageState] = useState<Language>(() => {
    try {
      return localStorage.getItem('friday-language') === 'zh' ? 'zh' : 'en'
    } catch {
      return 'en'
    }
  })

  const setLanguage = (lang: Language) => {
    setLanguageState(lang)
    localStorage.setItem('friday-language', lang)
  }

  const t = (key: TranslationKey, vars?: Record<string, string | number>) => {
    let value = translations[language][key] || translations.en[key] || key
    if (vars) {
      for (const [name, val] of Object.entries(vars)) {
        value = value.replace(`{${name}}`, String(val))
      }
    }
    return value
  }

  return (
    <I18nContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </I18nContext.Provider>
  )
}

export function useI18n() {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n must be used within I18nProvider')
  return ctx
}

/** Localised label for a stored task category (values stay English at rest). */
export function categoryLabel(value: string | null | undefined, lang: Language): string {
  if (!value) return ''
  const key = `cat${value.charAt(0).toUpperCase()}${value.slice(1)}` as TranslationKey
  return translations[lang][key] ?? translations.en[key] ?? value
}

export function taskTypeLabel(type: string, lang: Language): string {
  if (type === 'longTerm') return translations[lang].typeLongTerm
  if (type === 'flexible') return translations[lang].typeFlexible
  return translations[lang].typeScheduled
}

export function taskStatusLabel(status: string, lang: Language): string {
  if (status === 'completed') return translations[lang].statusCompleted
  if (status === 'paused') return translations[lang].statusPaused
  if (status === 'active') return translations[lang].statusActive
  return translations[lang].statusScheduled
}
